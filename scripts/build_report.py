"""Write evals/REPORT.md from the latest eval reports (`make eval`, spec §11).

Reads `evals/reports/{model,decisions,summaries,latency}.json` (evalgate.report.v1) and the baselines in
`evals/reports/baseline/`, and states the mode (offline, cassette or live), the models and prompt hash, every
metric against its threshold and baseline, the gate verdict per suite, and the command behind each number.
The file is generated only from the reports (no wall-clock time), so the same reports give the same file.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from evalgate.contracts import Report  # noqa: E402
from evalgate.gate import check  # noqa: E402
from fraud_summarizer.pipeline import PROMPT_VERSION, load_prompt, prompt_hash  # noqa: E402

REPORTS = ROOT / "evals" / "reports"
SUITES = [
    ("model", "make eval-model", "2M-event eval data, temporal test split; serving ONNX artifact + Go rules"),
    ("decisions", "make eval-decisions", "150 golden transactions (test 90), real scorer via cmd/evaldecide"),
    ("summaries", "make eval-summary", "120 REVIEW cases (test 72), real summary pipeline"),
    ("latency", "make bench", "Score under constant load (ghz), host stack"),
]


def _load(path: Path) -> tuple[Report, str] | None:
    if not path.is_file():
        return None
    raw = path.read_bytes()
    return Report.model_validate(json.loads(raw)), hashlib.sha256(raw).hexdigest()


def _num(name: str, v: float) -> str:
    return f"{v:.1f} ms" if name.endswith("_ms") else f"{v:.4f}"


def _threshold(direction: str, t: float | None) -> str:
    return "–" if t is None else f"{'≥' if direction == 'higher' else '≤'} {t:g}"


def _delta(name: str, v: float, b: float) -> str:
    return f"{v - b:+.1f} ms" if name.endswith("_ms") else f"{(v - b) * 100:+.2f}"


def mode_of(reports: dict[str, Report]) -> str:
    if any(r.mode == "live" for r in reports.values()):
        return "live"
    summaries = reports.get("summaries")
    if summaries and any(not m.startswith("fake-") for m in summaries.models):
        return "cassette"  # offline run answered from recorded provider responses
    return "offline"


def _details(name: str, r: Report) -> list[str]:
    ext = r.extensions or {}
    if name == "model":
        data = ext.get("data", {})
        op = ext.get("operating_point_from_valid", {})
        return [
            f"Data: {data.get('events', '?'):,} events, gen v{data.get('gen_version', '?')}, seed {data.get('seed', '?')}, "
            f"sha256 {str(data.get('events_sha256', ''))[:12]}; test split {ext.get('n_transactions', 0):,} transactions, "
            f"{ext.get('n_fraud', 0):,} fraud.",
            f"Model {', '.join(r.models)} (feature spec {ext.get('feature_spec')}, onnx sha256 {str(ext.get('onnx_sha256', ''))[:12]}); "
            f"rules alone flag {ext.get('rules_fpr', 0) * 100:.2f}% of legitimate transactions.",
            f"Threshold chosen on valid: test recall {op.get('test_recall', 0):.4f} at FPR {op.get('test_fpr', 0) * 100:.2f}%.",
            f"Cases: {ext.get('case_unit', 'shards')}.",
        ]
    if name == "latency":
        lines = [
            f"Profile {ext.get('profile')}: {ext.get('achieved_rps', 0):.0f} of {ext.get('target_rps', 0):.0f} rps for "
            f"{ext.get('duration_s', 0):.0f} s; p50 {r.latency_p50_ms:.1f} ms, p95 {r.latency_p95_ms:.1f} ms, "
            f"p99 {ext.get('p99_ms', 0):.1f} ms (budget p95 {ext.get('budget', {}).get('max_p95_ms', '?')} ms).",
        ]
        if "decisions" in ext:
            lines.append(f"Degraded decisions in the window: {ext['degraded']:,} of {ext['decisions']:,}.")
        return lines
    lines = [
        f"{r.n_cases} cases ({ext.get('split', '?')} split), dataset sha256 {str(ext.get('dataset_sha256', ''))[:12]}; "
        f"p50 {r.latency_p50_ms:.1f} ms, p95 {r.latency_p95_ms:.1f} ms; cost USD {r.cost_usd_total:.4f}."
    ]
    if r.models:
        lines.append(f"Models: {', '.join(r.models)}.")
    return lines


def render(reports_dir: Path, baseline_dir: Path) -> str:
    loaded = {name: _load(reports_dir / f"{name}.json") for name, _, _ in SUITES}
    present = {name: v[0] for name, v in loaded.items() if v is not None}
    system = load_prompt(PROMPT_VERSION)
    out = [
        "# Eval report",
        "",
        "<!-- Generated by scripts/build_report.py from evals/reports/*.json (`make eval`); do not edit by hand. -->",
        "",
        f"Mode: **{mode_of(present)}**. Prompt {PROMPT_VERSION} (sha256 {prompt_hash(system)[:12]}). "
        f"Commit {next((r.git_sha[:10] for r in present.values() if r.git_sha), 'unknown')}.",
        "",
    ]
    rows, sections, verdicts = [], [], []
    for name, command, data in SUITES:
        item = loaded[name]
        if item is None:
            sections += [f"## {name}", "", f"{name}: not run (`{command}`).", ""]
            continue
        rep, sha = item
        base_item = _load(baseline_dir / f"{name}.json")
        base = base_item[0] if base_item else None
        result = check(
            rep,
            report_sha256=sha,
            baseline=base,
            baseline_sha256=base_item[1] if base_item else None,
            max_regression_pp=1.0,
        )
        verdicts.append(result.passed)
        for metric, s in rep.metrics.items():
            b = base.metrics.get(metric) if base else None
            status = "pass" if s.passed else "**FAIL**"
            rows.append(
                f"| {name} | {metric} | {_num(metric, s.value)} | {_threshold(s.direction, s.threshold)} | {status} | "
                f"{_num(metric, b.value) if b else '–'} | {_delta(metric, s.value, b.value) if b else '–'} |"
            )
        sections += [f"## {name}", "", f"Command: `{command}`. {data}.", ""]
        sections += [f"- {line}" for line in _details(name, rep)]
        gate = "PASS" if result.passed else "FAIL"
        reasons = "; ".join(f"{f.metric} {f.reason}" for f in result.failures)
        sections += [
            f"- `evalgate check` {'against the baseline' if base else 'without a baseline'}: **{gate}**"
            + (f" ({reasons})" if reasons else "")
            + ".",
            "",
        ]
    live = _load(reports_dir / "summaries_live.json")
    if live is None:
        live_line = (
            "Live evals (`make eval-live`): not run — no provider key in this environment; every number above "
            "is offline (spec §19 step 4)."
        )
    else:
        lr = live[0]
        live_line = (
            f"Live evals (`make eval-live`): run {lr.created_at[:10]} on {', '.join(lr.models)}, cost USD "
            f"{lr.cost_usd_total:.4f}: "
            + ", ".join(
                f"{m} {s.value:.4f} ({'pass' if s.passed else 'FAIL'})" for m, s in lr.metrics.items()
            )
            + "."
        )
    gate_all = "PASS" if verdicts and all(verdicts) else "FAIL"
    out += [
        f"Gate: **{gate_all}** ({sum(verdicts)} of {len(verdicts)} suites pass; thresholds from spec §11, "
        "regressions over 1 pp with a 95% paired-bootstrap interval excluding 0).",
        "",
        live_line,
        "",
        "| Suite | Metric | Value | Threshold | Status | Baseline | Δ (pp) |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
        *sections,
    ]
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--reports", type=Path, default=REPORTS)
    parser.add_argument("--baseline", type=Path, default=REPORTS / "baseline")
    parser.add_argument("--out", type=Path, default=ROOT / "evals" / "REPORT.md")
    args = parser.parse_args(argv)
    text = render(args.reports, args.baseline)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out}")
    return 0 if "Gate: **PASS**" in text else 1


if __name__ == "__main__":
    raise SystemExit(main())
